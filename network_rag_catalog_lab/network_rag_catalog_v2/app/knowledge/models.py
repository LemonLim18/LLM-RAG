"""Typed shared definitions, operation contracts and template bindings."""

# Annotated adds specific metadata/constraint to a type
from typing import Annotated, Literal

from jsonschema import Draft202012Validator
from pydantic import BaseModel, ConfigDict, Field, JsonValue, StringConstraints, model_validator

# This is a special constrained string type that is used for stable identifiers, which requires first characters to be lowercase letters, and the following characters to be lowercase, number, underscore.
StableId = Annotated[str, StringConstraints(pattern=r"^[a-z][a-z0-9_]*$")]
# must have at least one non-whitespace character
NonBlankText = Annotated[str, StringConstraints(min_length=1, pattern=r"\S")]
FieldPath = Annotated[str, StringConstraints(pattern=r"^[A-Za-z_][A-Za-z0-9_]*(?:\[\]|\.[A-Za-z_][A-Za-z0-9_]*)*$")]
NodePath = Annotated[str, StringConstraints(pattern=r"^(?:[A-Za-z_][A-Za-z0-9_]*(?:\[\]|\.[A-Za-z_][A-Za-z0-9_]*)*)?$")]

# CatalogRecord is the base class for all catalog records, which includes Category, ParameterDefinition, and Operation.
# They contain the same fields: display_name, aliases, and description.
class CatalogRecord(BaseModel):
    model_config = ConfigDict(strict=True, frozen=True, extra="allow")

    display_name: NonBlankText
    aliases: list[NonBlankText] = Field(default_factory=list)
    description: str = ""

    def to_legacy_dict(self) -> dict:
        # Do not inject model defaults into existing callers' dictionary payloads.
        return self.model_dump(exclude_unset=True)

# Each category follows the CatalogRecord structure, and has a unique category_id and a status that can be either "active" or "inactive".
class Category(CatalogRecord):
    category_id: StableId
    # status field allows the deactivation of a category without deleting it, which is useful for maintaining historical data and references. 
    # Deletion is avoided because the other many things like old operations, audit history, old clarification session, etc may still reference it.
    status: Literal["active", "inactive"] = "active"

# ParameterDefinition describes the parameter's type, clarification, and optional normalizer.
# The normalizer is a function that takes the parameter's value and returns a normalized value. The normalizer is optional, and if not provided, the parameter's value will be used as-is.
class ParameterDefinition(CatalogRecord):
    parameter_id: StableId
    value_type: Literal["string", "integer", "number", "boolean", "array", "object", "null"]
    clarification: str = ""
    # the normalizer doest not perform the normalization itself, but stores the name of the noramlizer function that is defined in the codebase.
    normalizer: NonBlankText | None = None

    @model_validator(mode="before")
    @classmethod
    def reject_operation_policies(cls, value):
        # Add the other self-defined keywords along with the standard JSON Schema keyword to the set of policy keys.
        # The purpose of this is to ensure that any operation rules are not mistakenly included in shared parameters, as they belong in operation schemas. If any of these are found in the parameter definition, a ValueError is raised to alert the user.
        policy_keys = set(Draft202012Validator.VALIDATORS) | {
            "optional", "validation", "validation_rules", "rules", "schema", "default", "x-required-by-vendor",
        }
        if isinstance(value, dict) and (found := policy_keys.intersection(value)):
            raise ValueError(f"Operation rules belong in operation schemas, not shared parameters: {sorted(found)}")
        return value


class CategoryParameter(BaseModel):
    """Membership only; labels/types remain on the referenced definition."""

    model_config = ConfigDict(strict=True, frozen=True, extra="forbid")

    category_id: StableId
    parameter_id: StableId


class VendorIntentKnowledge(BaseModel):
    """Intent recognition is independent of reviewed configuration support."""

    model_config = ConfigDict(strict=True, frozen=True, extra="forbid")

    # This status field allows the user to know whether the vendor has provided support for the operation, or if it is blocked due to unverified intent.
    status: Literal["generation_supported", "blocked_unverified"]
    reason: NonBlankText
    requirements: list[NonBlankText] = Field(default_factory=list)


class Operation(CatalogRecord):
    operation_id: StableId
    category_id: StableId
    # This tells the path of the schema for this operation
    schema_path: str = ""
    status: Literal["active", "inactive"] = "active"
    version: Annotated[int, Field(ge=1)] = 1
    use_cases: list[NonBlankText] = Field(default_factory=list)
    # let know if the schema comes from legacy which is the physical schema_path/old schema file, or registry which the normalized knowledge generated by schema compiler.
    schema_source: Literal["legacy", "registry"] = "legacy"
    # If legacy is still authoratative, shoudl the new registry representation also be compiled just for comparison?
    mapping_mode: Literal["none", "compare"] = "none"
    # It helps answer if the system uynderstand what the user is asking but the template is not revieweed yet to say unknown operation
    # generation_supported means the system can generate the configuration for this operation, blocked_unverified means the system cannot generate the configuration for this operation because the intent is not verified by the vendor yet.
    vendor_knowledge: dict[StableId, VendorIntentKnowledge] = Field(default_factory=dict)

    @model_validator(mode="after")
    def check_authority(self):
        if self.schema_source == "legacy" and not self.schema_path.strip():
            raise ValueError("Legacy operations require a schema_path.")
        if self.schema_source == "registry" and self.mapping_mode != "none":
            raise ValueError("Registry authority cannot also be comparison-only.")
        return self

# TemplateInputContract describes the contract or expectation rules for the fields in the template that the template must fulfill in order to be considered a valid implementation of the operation. The input contract is used to validate that the template can be used to generate the correct configuration for the operation.
# The fields are the required fields that must be present in the template for it to be considered a valid implementation of the operation. For example, if a template has required fields "vlan_id" and "name", the fields would be ["vlan_id", "name"].
# The optional_defaults are the optional fields that may be present in the template, and their default values if they are not present. For example, if a template has an optional field "description" that is not present, the optional_defaults would be {"description": None}.
# The derived fields are the fields that are derived from other fields in the template, and their derivation expressions. For example, if a template has a field "vlan_name" that is derived from the "vlan_id" field, the derived field would be {"vlan_name": "vlan_{vlan_id}"}.
class TemplateInputContract(BaseModel):
    model_config = ConfigDict(strict=True, frozen=True, extra="forbid") # frozen=True makes the model immutable by other code

    fields: list[NonBlankText]
    optional_defaults: dict[str, None] = Field(default_factory=dict)
    derived: dict[str, str] = Field(default_factory=dict)


class ConditionalRequirement(BaseModel):
    model_config = ConfigDict(strict=True, frozen=True, extra="forbid")

    field: NonBlankText
    equals: JsonValue
    required: Annotated[list[NonBlankText], Field(min_length=1)]

# operation_id, operation_version for locking in the specific operation under the correct version
# TemplateBinding specifies which actual configuration template(hinted by path) implements this operation for this vendor(cisco)/platform(iosxe,nxos,iosxr: which can use different command syntax)/version (1.12.0, 1.13.0, 2.0.0)
# TemplateInputContract describes which fields like vlan_id, name, description, etc. are required to consider the template specified by the path to be a valid implementation of the operation. The input contract is used to validate that the template can be used to generate the correct configuration for the operation.
class TemplateBinding(BaseModel):
    model_config = ConfigDict(strict=True, frozen=True, extra="forbid")

    operation_id: StableId
    operation_version: Annotated[int, Field(ge=1)]
    vendor: StableId
    platform: StableId
    versions: Annotated[list[NonBlankText], Field(min_length=1)]
    template_path: NonBlankText
    input_contract: TemplateInputContract

# Mappings tell the compile what fields should exist
# operation_id, operation_version, field_path is used to lock in the specific operation under the correct version
# create_vlan.vlan_id (Operation + Parameter)
# mapping already contains the required field
class OperationParameterMapping(BaseModel):
    model_config = ConfigDict(strict=True, frozen=True, extra="forbid")

    operation_id: StableId
    operation_version: Annotated[int, Field(ge=1)]
    category_id: StableId
    parameter_id: StableId
    # where inside the operation's input schema the parameter is expected to be found because parameters may be nested
    # field_path = configure_ospf.interfaces[].name, not simply 'name'
    # field_path = create_vlan.name, this helps differentiatee between parameters with the same name in different operations
    field_path: FieldPath
    # for the deterministic ordering of parameters in the operation's input schema
    position: Annotated[int, Field(ge=0)]
    required: bool
    # Give the parameter its ordering among required fields, or None if the parameter is optional. This is used to ensure that required fields are presented in a consistent order, which can be important for user interfaces and documentation.
    required_order: Annotated[int, Field(ge=0)] | None = None

    @model_validator(mode="after")
    def check_required_order(self):
        # required field must have a required_order, optional field must not have a required_order
        if self.required != (self.required_order is not None):
            raise ValueError("Required fields need a required_order; optional fields must use null.")
        # it should not be an array item, but refers to a named property
        if self.field_path.endswith("[]"):
            raise ValueError("Mappings identify named properties, not anonymous array items.")
        return self

# Rule tells the compiler 
"""
keywords = {
    "minimum": 1,
    "maximum": 4094
}
"""
class OperationSchemaRule(BaseModel):
    model_config = ConfigDict(strict=True, frozen=True, extra="forbid")

    operation_id: StableId
    operation_version: Annotated[int, Field(ge=1)]
    field_path: NodePath  # NodePath allows for empty string, which is used to indicate the root of the operation's input schema
    # JsonValue means the values must be representable in JSON.
    keywords: dict[str, JsonValue]

    # This validator ensures that the required keywords is not used in the Schema Rule, but only used in the mapping for the purpose of the avoiding conflict.
    @model_validator(mode="after")
    def check_structural_keywords(self):
        if set(self.keywords) & {"properties", "items", "required"}:
            raise ValueError("Property structure and required flags belong to mappings, not rule keywords.")
        return self
